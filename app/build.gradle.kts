/**
 * Client configuration is read from (in order): environment variables, then `local.properties`.
 * Only PUBLIC values belong here (e.g. the Findly backend base URL). Third-party API keys and
 * affiliate secrets live on the backend, never in the APK. See docs/CONFIGURATION.md.
 */
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

fun config(key: String, default: String = ""): String =
    System.getenv(key) ?: localProps.getProperty(key) ?: default

